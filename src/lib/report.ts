/**
 * Downloadable writing report (self-contained HTML) and small download helpers.
 */
import type { DetectionResult } from "@/lib/engine/types";
import { SITE } from "@/lib/site";

export function downloadTextFile(filename: string, content: string, mime = "text/plain"): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

export const VERDICT_TEXT = {
  human: "Likely human-written",
  mixed: "Mixed signals",
  ai: "Likely AI-generated",
} as const;

export function scoreNote(aiProbability: number, tooShort: boolean): string | null {
  if (tooShort) return "Too short for a reliable score. Add more text.";
  if (aiProbability > 0 && aiProbability < 20)
    return "Scores under 20% are less reliable, so sentences are not highlighted by default.";
  return null;
}

/** Build a standalone HTML report the user can save or share. */
export function buildReportHtml(text: string, result: DetectionResult, title = "Writing report"): string {
  const generated = new Date().toLocaleString("en-US", { dateStyle: "medium", timeStyle: "short" });
  const dim = result.aiProbability < 20;
  let cursor = 0;
  let body = "";
  for (const s of result.sentences) {
    if (s.start > cursor) body += escapeHtml(text.slice(cursor, s.start));
    const cls = dim ? "" : s.verdict === "ai" ? "ai" : s.verdict === "mixed" ? "mixed" : "";
    body += `<span class="${cls}" title="${escapeHtml(s.signals.join("; "))}">${escapeHtml(
      text.slice(s.start, s.end),
    )}</span>`;
    cursor = s.end;
  }
  body += escapeHtml(text.slice(cursor));

  const rows = result.detectors
    .map(
      (d) =>
        `<tr><td>${escapeHtml(d.name)}</td><td>${
          d.unavailable ? `<em>${escapeHtml(d.note ?? "Unavailable")}</em>` : `${d.aiScore}% AI`
        }</td><td class="${d.verdict}">${d.unavailable ? "—" : VERDICT_TEXT[d.verdict]}</td></tr>`,
    )
    .join("");

  const flags = result.flags.length
    ? `<ul>${result.flags.map((f) => `<li><strong>${escapeHtml(f.label)}</strong>${f.count ? ` (${f.count})` : ""} — ${escapeHtml(f.description)}</li>`).join("")}</ul>`
    : "<p>No flags. A flag is not necessarily an indicator of a problem.</p>";

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${escapeHtml(title)} — ${SITE.name}</title>
<style>
body{font-family:ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif;color:#111318;margin:0;background:#f7f7f8}
.page{max-width:900px;margin:0 auto;padding:40px 24px}
.card{background:#fff;border:1px solid #e6e8ec;border-radius:16px;padding:28px;margin-bottom:20px}
h1{font-size:22px;margin:0 0 4px}h2{font-size:14px;text-transform:uppercase;letter-spacing:.12em;color:#9aa0ab;margin:0 0 12px}
.score{font-size:48px;font-weight:600;letter-spacing:-.02em}.muted{color:#6b7180;font-size:13px}
.doc{white-space:pre-wrap;line-height:1.8;font-size:15px}
.ai{background:rgba(220,76,76,.18);border-radius:4px}.mixed{background:rgba(212,138,11,.22);border-radius:4px}
table{width:100%;border-collapse:collapse;font-size:14px}td{padding:8px 0;border-top:1px solid #e6e8ec}
td.human{color:#1f9d63}td.mixed{color:#d48a0b}td.ai{color:#dc4c4c}
.legend span{display:inline-block;width:12px;height:12px;border-radius:3px;margin-right:6px;vertical-align:middle}
</style></head><body><div class="page">
<div class="card"><h1>${escapeHtml(title)}</h1><div class="muted">Generated by ${SITE.name} · ${escapeHtml(generated)}</div>
<div class="score" style="margin-top:16px">${result.aiProbability}%</div>
<div class="muted">of qualifying text is likely AI-generated · ${VERDICT_TEXT[result.verdict]} · confidence ${result.confidence}</div>
<p class="muted legend" style="margin-top:14px"><span style="background:rgba(220,76,76,.18)"></span>AI-generated (${result.breakdown.ai} sentences) &nbsp; <span style="background:rgba(212,138,11,.22)"></span>Mixed (${result.breakdown.mixed}) &nbsp; <span style="background:#e6f6ee"></span>Human-like (${result.breakdown.human})</p></div>
<div class="card"><h2>Document</h2><div class="doc">${body}</div></div>
<div class="card"><h2>Detector estimates</h2><table>${rows}</table>
<p class="muted">Estimates come from ${SITE.name}'s own model tuned to each detector's known behaviour. They are not live results from those services.</p></div>
<div class="card"><h2>Flags</h2>${flags}</div>
<div class="card"><h2>About this score</h2><p class="muted">The percentage is our estimate of how much of the qualifying text was likely generated by AI. The model may misidentify human-written and AI-generated text, so this report should not be the sole basis for any decision about authorship. It is data to support human judgement, not a determination of misconduct.</p></div>
</div></body></html>`;
}
